def _squash_spaced(t: str) -> str:
    """«з а к л а д к и» / «з.а.к.л.а.д.к.и» → «закладки» (только цепочки одиночных букв)."""
    return re.sub(r"\b(?:\w[\s.\-_*•·|]{1,2}){3,}\w\b", lambda m: re.sub(r"[\s.\-_*•·|]", "", m.group(0)), t)


def normalize(text: str) -> tuple[str, ...]:
    """Формы для проверки: «как есть» (английские слова), «похожие буквы → кириллица» и транслит (z4kl4dk1)."""
    t = (text or "").lower().replace("ё", "е")
    t = _squash_spaced(t)
    t = re.sub(r"(.)\1{2,}", r"\1\1", t)                      # «закладкииии» → «закладкии»
    plain = re.sub(r"\s+", " ", t)
    cyr = plain.translate(_LAT2CYR)
    tr = plain.translate(_TRANSLIT)
    return plain, cyr, tr


