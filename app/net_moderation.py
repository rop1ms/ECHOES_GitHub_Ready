_COMPILED = {cat: [re.compile(p, re.IGNORECASE) for p in pats] for cat, pats in PATTERNS.items()}


def check(text: str):
    """Есть запрещённое → (категория, найденный фрагмент), иначе None."""
    if not text or not text.strip():
        return None
    for form in normalize(text):
        for cat, pats in _COMPILED.items():
            for rx in pats:
                m = rx.search(form)
                if m:
                    return cat, m.group(0)[:60]
    return None


def check_many(*texts):
    for t in texts:
        r = check(t if isinstance(t, str) else "")
        if r:
            return r
    return None


def reason(cat: str) -> str:
    return CATEGORY.get(cat, cat)
